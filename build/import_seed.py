"""Refresh config/people_seed.yml from Percona's public ranking.json.

Credit: Percona-Lab/percona-pg-activity. Only person -> company labels are
used. Corrections belong in people.yml (it takes precedence). If the source is
unreachable the existing seed file is kept.
"""
import requests
import yaml

from common import CONFIG

URL = "https://percona-lab.github.io/percona-pg-activity/ranking.json"
HEADER = """# Seed person -> company labels imported from the Percona PostgreSQL activity
# dashboard (https://github.com/Percona-Lab/percona-pg-activity, ranking.json).
# Credit: Percona-Lab. Generated by build/import_seed.py; do not edit by hand --
# put corrections in people.yml, which takes precedence.
"""


def main():
    try:
        d = requests.get(URL, timeout=30).json()
    except Exception as e:  # noqa: BLE001
        print(f"seed refresh skipped: {e}")
        return
    people = [{"name": p["name"], "company": p["company"]} for p in d.get("people", [])
              if p.get("company") and p["company"] != "Unattributed"]
    body = {"generated_from": URL, "generated_at": d.get("generated_at"), "people": people}
    (CONFIG / "people_seed.yml").write_text(
        HEADER + yaml.safe_dump(body, allow_unicode=True, sort_keys=False))
    print(f"{len(people)} seed people")


if __name__ == "__main__":
    main()
